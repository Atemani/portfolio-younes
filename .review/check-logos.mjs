import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
const browser=await chromium.launch({channel:'chrome'});
const errors=[];
for(const width of [1440,1920,768,390,320]){
 const page=await browser.newPage({viewport:{width,height:900}});
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:4173/portfolio');
 const section=page.locator('.cp-project-logos');
 await section.scrollIntoViewIfNeeded();
 const images=section.locator('img');
 await images.evaluateAll(els=>Promise.all(els.map(el=>el.decode())));
 assert.equal(await section.locator('a,button,[role="button"]').count(),0);
 assert.equal(await section.locator('ul:not([aria-hidden]) img').count(),6);
 assert.equal(await section.locator('ul[aria-hidden="true"] img[alt=""]').count(),6);
 assert.ok(await section.evaluate(el=>el.previousElementSibling.classList.contains('cp-hero')));
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.ok(await images.evaluateAll(els=>els.every(el=>el.naturalWidth>0 && getComputedStyle(el).cursor==='default')));
 const seq=await section.locator('ul').evaluateAll(els=>els.map(el=>el.getBoundingClientRect().width));
 assert.ok(Math.abs(seq[0]-seq[1])<.1,'Loop halves match');
 await page.mouse.move(0,0);
 const a=await section.locator('.cp-project-logos-track').evaluate(el=>getComputedStyle(el).transform);
 await page.waitForTimeout(150);
 const b=await section.locator('.cp-project-logos-track').evaluate(el=>getComputedStyle(el).transform);
 assert.notEqual(a,b,'Marquee moves');
 await section.locator('.cp-project-logos-window').hover();
 assert.equal(await section.locator('.cp-project-logos-track').evaluate(el=>getComputedStyle(el).animationPlayState),'paused');
 await page.mouse.move(0,0);
 await section.locator('.cp-project-logos-window').focus();
 assert.equal(await section.locator('.cp-project-logos-track').evaluate(el=>getComputedStyle(el).animationPlayState),'paused');
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await section.locator('.cp-project-logos-track').evaluate(el=>getComputedStyle(el).animationName),'none');
 assert.equal(await section.locator('ul[aria-hidden="true"]').isVisible(),false);
 assert.ok(await images.first().evaluate(el=>el.getBoundingClientRect().width>0));
 await page.goto('http://127.0.0.1:4173/');
 assert.equal(await page.locator('.cp-project-logos').count(),0);
 assert.equal(await page.locator('.hotspot').count(),12);
 await page.locator('[data-object="cafe"]').click();
 await page.locator('dialog[open]').waitFor();
 await page.keyboard.press('Escape');
 await page.locator('dialog').waitFor({state:'detached'});
 console.log('Carrousel et bureau validés : '+width+' px');
 await page.close();
}
await browser.close();
assert.deepEqual(errors,[]);
